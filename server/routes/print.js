const crypto = require('crypto');
const express = require('express');
const db = require('../db');
const { requireAuth, requireRole } = require('../middleware/auth');

const router = express.Router();

const COMPANY = {
  name: 'DeepKamal Electrical & Fire Safety',
  gstin: process.env.COMPANY_GSTIN || '27AAAAA0000A1Z5',
  address: process.env.COMPANY_ADDRESS || 'Mumbai / NCR operations',
  phone: process.env.COMPANY_PHONE || '',
  email: process.env.COMPANY_EMAIL || 'ops@deepkamal.in'
};

function money(n) {
  return '₹' + Number(n || 0).toLocaleString('en-IN', { minimumFractionDigits: 2, maximumFractionDigits: 2 });
}

function issueToken(entityType, entityId, hours = 72) {
  const token = crypto.randomBytes(16).toString('hex');
  const expires = new Date(Date.now() + hours * 3600 * 1000).toISOString();
  db.prepare(`INSERT INTO print_tokens (token, entity_type, entity_id, expires_at) VALUES (?, ?, ?, ?)`).run(
    token,
    entityType,
    entityId,
    expires
  );
  return token;
}

function resolveToken(token) {
  const row = db.prepare(`SELECT * FROM print_tokens WHERE token = ?`).get(token);
  if (!row) return null;
  if (row.expires_at < new Date().toISOString()) return null;
  return row;
}

